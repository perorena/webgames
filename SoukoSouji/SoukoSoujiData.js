/*
0:空間（ゲーム開始時は無い・ゴミを取ると空間になる・空間はプレーヤーは通れない）
1:壁
2:荷物
3:ゴミ
4:プレーヤー

プレーヤーがゴミを掃除していくゲーム
壁は突き抜けられず
ゴミがあるところだけを動ける
一筆書き掃除ゲーム
マス目数は拘らない
先にアドバイス
作る手順は、
１大枠の壁を作る（正方形か長方形）
２その中で自由に一筆書きを描く
３一筆書き以外のところに荷物を置く
４一筆書きをした最初の位置か最後の位置にプレーヤーを配置する
※一本道である必要はなく、広い場所があればそこを一筆書きで通過できればいい

これまでに作った10問を参考に！
*/

